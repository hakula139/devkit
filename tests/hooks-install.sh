#!/usr/bin/env bash
set -euo pipefail

config="${1}"
shellHook="${2}"

export HOME="$TMPDIR/home"
export PRE_COMMIT_HOME="$TMPDIR/pre-commit"
export PREK_HOME="$TMPDIR/prek"
export GIT_CONFIG_NOSYSTEM=1
export GIT_CONFIG_GLOBAL=/dev/null
mkdir -p "$HOME" "$PRE_COMMIT_HOME" "$PREK_HOME"

repo="$TMPDIR/repo"
mkdir -p "$repo"
cd "$repo"
git init --quiet
git config user.email test@example.com
git config user.name Test
ln -s "$config" .pre-commit-config.yaml

pre-commit install --config "$config" --hook-type pre-commit --hook-type pre-push
grep -q 'File generated by pre-commit' .git/hooks/pre-commit

bash -euo pipefail -c "$shellHook"
bash -euo pipefail -c "$shellHook"

grep -q 'File generated by prek' .git/hooks/pre-commit
grep -q 'File generated by prek' .git/hooks/pre-push
test ! -e .git/hooks/pre-commit.legacy
test ! -e .git/hooks/pre-push.legacy
git commit --allow-empty --message check
